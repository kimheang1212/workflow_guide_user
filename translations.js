// Current language
let currentLanguage = 'en';

// Function to update all text content based on selected language
function updateLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('preferredLanguage', lang);
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            // Handle different element types
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translations[lang][key];
            } else {
                element.innerHTML = translations[lang][key];
            }
        }
    });
    
    // Update language switcher button text
    const langButton = document.getElementById('language-switcher');
    if (langButton) {
        langButton.textContent = lang === 'en' ? translations[lang]['switch_to_khmer'] : translations[lang]['switch_to_english'];
    }
    
    // Update HTML lang attribute
    document.documentElement.lang = lang;
}

// Function to toggle language
function toggleLanguage() {
    const newLang = currentLanguage === 'en' ? 'km' : 'en';
    updateLanguage(newLang);
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    // Check for saved language preference
    const savedLang = localStorage.getItem('preferredLanguage') || 'en';
    updateLanguage(savedLang);
    
    // Add click event to language switcher
    const langButton = document.getElementById('language-switcher');
    if (langButton) {
        langButton.addEventListener('click', toggleLanguage);
    }
});